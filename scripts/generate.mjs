import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { relative, resolve } from 'node:path'
import { compileScript, parse } from '@vue/compiler-sfc'
import { localizeComponents } from './catalog-i18n.mjs'
import { components, origin, version } from './catalog.mjs'
import { extractProps } from './component-contract.mjs'

for (const path of ['package.json', 'packages/core/package.json', 'packages/augma/package.json']) {
  const pkg = JSON.parse(await readFile(path, 'utf8'))
  if (pkg.version !== version)
    throw new Error(`${path} must match component contract v${version}`)
}
const site = resolve('apps/site')
const publicDir = resolve(site, 'public')
for (const dir of ['r', 'markdown']) {
  await rm(resolve(publicDir, dir), { recursive: true, force: true })
  await mkdir(resolve(publicDir, dir), { recursive: true })
}
// One component page per docs locale. The Chinese catalog stays the source of components.json and the Registry.
// `required` replaces the 必填 default that component-contract.mjs gives required props.
const docs = {
  'zh-CN': { dir: 'components', usage: '基础用法', columns: '| 属性 | 类型 | 默认值 | 说明 |', required: '必填', events: '事件', slots: '插槽', keyboard: '键盘操作与使用边界', install: '安装', registry: '复制可编辑源码：' },
  'en-US': { dir: 'en/components', usage: 'Basic usage', columns: '| Prop | Type | Default | Description |', required: 'Required', events: 'Events', slots: 'Slots', keyboard: 'Keyboard and usage notes', install: 'Installation', registry: 'Copy the editable source:' },
  'ja-JP': { dir: 'ja/components', usage: '基本的な使い方', columns: '| プロパティ | 型 | デフォルト | 説明 |', required: '必須', events: 'イベント', slots: 'スロット', keyboard: 'キーボード操作と利用上の注意', install: 'インストール', registry: '編集可能なソースをコピー：' },
}
const pages = Object.fromEntries(
  Object.keys(docs).map(locale => [locale, new Map(localizeComponents(locale).map(item => [item.slug, item]))]),
)
for (const { dir } of Object.values(docs))
  await mkdir(resolve(site, dir), { recursive: true })
const index = []
for (const item of components) {
  const source = await readFile(
    `packages/augma/src/components/${item.name}.vue`,
    'utf8',
  )
  const { descriptor } = parse(source)
  const compiled = compileScript(descriptor, { id: item.slug })
  const declarations = extractProps(descriptor, compiled)
  if (declarations.size !== item.props.length) {
    throw new Error(
      `${item.name}: describe every public property in the catalog`,
    )
  }
  item.props = item.props.map((prop) => {
    const declaration = declarations.get(prop.name)
    if (!declaration)
      throw new Error(`${item.name}: undocumented or unknown prop ${prop.name}`)
    return { ...declaration, description: prop.description }
  })
  for (const [locale, copy] of Object.entries(docs)) {
    const page = pages[locale].get(item.slug)
    const api = item.props
      .map(
        p =>
          `| \`${p.name}\` | ${p.type.replaceAll('|', '\\|')} | ${p.default === '必填' ? copy.required : p.default} | ${page.props.find(({ name }) => name === p.name).description} |`,
      )
      .join('\n')
    const doc = `<!-- Generated by scripts/generate.mjs from the public catalog. -->\n# ${page.title}\n\n${page.description}\n\n## ${copy.usage}\n\n<DemoPreview name="${item.slug}" />\n\n## API\n\n${copy.columns}\n| --- | --- | --- | --- |\n${api}\n\n${item.events ? `### ${copy.events}\n\n${item.events.map(e => `- \`${e}\``).join('\n')}\n\n` : ''}${page.slots ? `### ${copy.slots}\n\n${page.slots.map(s => `- ${s}`).join('\n')}\n\n` : ''}## ${copy.keyboard}\n\n${page.keyboard}\n\n## ${copy.install}\n\n\`\`\`ts\nimport { ${item.name} } from 'augma'\nimport 'augma/style.css'\n\`\`\`\n${item.registry ? `\n${copy.registry}\n\n\`\`\`sh\npnpm dlx shadcn-vue@2.8.2 add ${origin}/r/${item.slug}.json\n\`\`\`\n` : ''}`
    await writeFile(resolve(site, `${copy.dir}/${item.slug}.md`), doc)
  }
  const entry = {
    ...item,
    version,
    import: `import { ${item.name} } from 'augma'`,
    url: `${origin}/components/${item.slug}`,
    example: `${origin}/markdown/examples/${item.slug}.vue`,
    registry: item.registry ? `${origin}/r/${item.slug}.json` : undefined,
  }
  index.push(entry)
  if (item.registry) {
    const deps = [`@augma/core@${version}`]
    if (source.includes('from \'reka-ui\''))
      deps.push('reka-ui@2.10.5')
    await writeFile(
      resolve(publicDir, `r/${item.slug}.json`),
      `${JSON.stringify({ $schema: 'https://shadcn-vue.com/schema/registry-item.json', name: item.slug, type: 'registry:ui', title: item.title, description: item.description, dependencies: deps, files: [{ path: `ui/augma/${item.name}.vue`, type: 'registry:ui', content: source }], docs: 'Import \'@augma/core/style.css\' once in your application entry. Vue 3.5+ is required. This source is yours to edit.' }, null, 2)}\n`,
    )
  }
}
await writeFile(
  resolve(publicDir, 'components.json'),
  `${JSON.stringify({ schemaVersion: 1, version, origin, components: index }, null, 2)}\n`,
)
await writeFile(
  resolve(publicDir, 'r/index.json'),
  `${JSON.stringify({ name: 'augma', homepage: origin, items: index.filter(c => c.registry).map(c => ({ name: c.slug, type: 'registry:ui', title: c.title, url: c.registry })) }, null, 2)}\n`,
)
// The Chinese examples stay at /markdown/examples/ and /markdown/compositions/; translations from
// examples/<locale>/ mirror them under /markdown/en/ and /markdown/ja/.
for (const [prefix, from] of [['', 'examples'], ['en/', 'examples/en-US'], ['ja/', 'examples/ja-JP']]) {
  await mkdir(resolve(publicDir, `markdown/${prefix}examples`), { recursive: true })
  for (const item of components) {
    await writeFile(
      resolve(publicDir, `markdown/${prefix}examples/${item.slug}.vue`),
      await readFile(`${from}/components/${item.slug}.vue`),
    )
  }
  await mkdir(resolve(publicDir, `markdown/${prefix}compositions`), { recursive: true })
  for (const file of await readdir(`${from}/compositions`)) {
    if (file.endsWith('.vue')) {
      await writeFile(
        resolve(publicDir, `markdown/${prefix}compositions`, file),
        await readFile(`${from}/compositions/${file}`),
      )
    }
  }
}
const documents = []
async function collect(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (
      entry.name.startsWith('.')
      || entry.name === 'public'
      || entry.name === 'node_modules'
    ) {
      continue
    }
    const path = resolve(dir, entry.name)
    if (entry.isDirectory()) {
      await collect(path)
    }
    else if (entry.name.endsWith('.md')) {
      const rel = relative(site, path)
      let content = (await readFile(path, 'utf8'))
        .replace(/^---\n[\s\S]*?\n---\n/, '')
        .replace(/<!--.*?-->/gs, '')
      const localePrefix = rel.match(/^(?:en|ja)\//)?.[0] ?? ''
      content = content.replace(
        /<DemoPreview name="([\w-]+)"\s*\/>/g,
        (_, slug) => `[Vue example](${origin}/markdown/${localePrefix}examples/${slug}.vue)`,
      )
      content = content.replace(
        /<(HomePage|ShowcasePage|DownloadPage|ComponentCatalog|ThemeComparison)\s*\/>/g,
        '',
      )
      const dest = resolve(publicDir, 'markdown', rel)
      await mkdir(resolve(dest, '..'), { recursive: true })
      await writeFile(dest, content)
      // llms-full.txt carries the Chinese source once; translations stay under /markdown/en/ and /markdown/ja/.
      if (!/^(?:en|ja)\//.test(rel))
        documents.push({ rel, content })
    }
  }
}
await collect(site)
await writeFile(
  resolve(publicDir, 'llms.txt'),
  `# Augma\n\n> AR-inspired design tokens and Vue 3 components. Version ${version}.\n\n- [Getting started](${origin}/markdown/guide/index.md)\n- [Design system](${origin}/markdown/design/index.md)\n- [AI integration](${origin}/markdown/ai/index.md)\n- [Component contract](${origin}/components.json)\n- [Complete documentation](${origin}/llms-full.txt)\n- [Agent Skill](https://github.com/YunYouJun/augma/blob/main/skills/augma/SKILL.md)\n\n## Components\n${index.map(c => `- [${c.name}](${origin}/markdown/components/${c.slug}.md): ${c.description}`).join('\n')}\n`,
)
await writeFile(
  resolve(publicDir, 'llms-full.txt'),
  `# Augma ${version}\n\n${documents.map(d => `Source: ${origin}/markdown/${d.rel}\n\n${d.content}`).join('\n\n---\n\n')}`,
)
// The Agent Skill carries an offline API reference and tested recipes, generated from the same
// catalog and English examples as the docs, so agents never have to guess props.
const skillReferences = resolve('skills/augma/references')
const english = pages['en-US']
const fence = (lang, code) => `\`\`\`${lang}\n${code.trimEnd()}\n\`\`\``
const sections = []
for (const item of components) {
  const page = english.get(item.slug)
  const rows = item.props
    .map(p => `| \`${p.name}\` | ${p.type.replaceAll('|', '\\|')} | ${p.default === '必填' ? 'Required' : p.default} | ${page.props.find(({ name }) => name === p.name).description} |`)
    .join('\n')
  const example = await readFile(`examples/en-US/components/${item.slug}.vue`, 'utf8')
  sections.push([
    `## ${item.name}`,
    `${page.title}: ${page.description}`,
    `| Prop | Type | Default | Description |\n| --- | --- | --- | --- |\n${rows}`,
    item.events && `Events: ${item.events.map(e => `\`${e}\``).join(', ')}`,
    page.slots && `Slots:\n\n${page.slots.map(s => `- ${s}`).join('\n')}`,
    `Usage notes: ${page.keyboard}`,
    item.registry && `Editable source: \`pnpm dlx shadcn-vue@2.8.2 add ${origin}/r/${item.slug}.json\``,
    `Docs: ${origin}/en/components/${item.slug}`,
    fence('vue', example),
  ].filter(Boolean).join('\n\n'))
}
await writeFile(
  resolve(skillReferences, 'components.md'),
  `<!-- Generated by scripts/generate.mjs from scripts/catalog.mjs and examples/en-US. Do not edit by hand. -->\n# Component reference\n\nAugma ${version}: ${components.length} Vue 3.5+ components. Each is a named export of \`augma\`; load the stylesheet once in the app entry.\n\n${fence('ts', `import { ${components[0].name} } from 'augma'\nimport 'augma/style.css'`)}\n\n${components.map(c => `- [${c.name}](#${c.name.toLowerCase()}): ${english.get(c.slug).description}`).join('\n')}\n\n${sections.join('\n\n')}\n`,
)
