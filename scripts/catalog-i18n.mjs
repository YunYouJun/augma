/**
 * The component catalog in one docs language.
 *
 * @param {'zh-CN' | 'en-US' | 'ja-JP'} locale - Docs language; `zh-CN` returns the source catalog
 * @returns The catalog entries with translated title, description, prop descriptions, slots and keyboard notes
 */
export function localizeComponents(locale) {
  if (locale === 'zh-CN')
    return components
  return components.map((item) => {
    const copy = translations[locale]?.[item.slug]
    if (!copy)
      throw new Error(`${locale}: translate ${item.slug} in scripts/catalog-i18n.mjs`)
    const extra = Object.keys(copy.props).filter(name => !item.props.some(prop => prop.name === name))
    if (extra.length)
      throw new Error(`${locale}: ${item.slug} has no props ${extra.join(', ')}`)
    if ((item.slots?.length ?? 0) !== (copy.slots?.length ?? 0))
      throw new Error(`${locale}: ${item.slug} must translate every slot`)
    return {
      ...item,
      title: copy.title,
      description: copy.description,
      props: item.props.map((prop) => {
        if (!copy.props[prop.name])
          throw new Error(`${locale}: translate ${item.slug} prop ${prop.name}`)
        return { ...prop, description: copy.props[prop.name] }
      }),
      slots: copy.slots,
      keyboard: copy.keyboard,
    }
  })
}
