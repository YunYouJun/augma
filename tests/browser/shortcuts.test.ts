import { expect, test } from '@playwright/test'

test('keyboard shortcuts open apps, toggle the view and stay out of text fields', async ({ page }) => {
  await page.goto('/ar/')
  const weather = page.getByRole('button', { name: '天气', exact: true })
  await expect(weather).toHaveAttribute('aria-keyshortcuts', 'W')
  await expect(weather).toHaveAttribute('data-tooltip', '天气 · W')

  await page.keyboard.press('w')
  await expect(page.locator('.device-window--weather')).toBeVisible()
  await page.keyboard.press('w')
  await expect(page.locator('.device-window')).toHaveCount(0)
  await page.keyboard.press('Shift+N')
  await expect(page.getByRole('heading', { name: '通知', exact: true })).toBeVisible()
  await page.keyboard.press(',')
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.device-window')).toHaveCount(0)

  await page.keyboard.press('d')
  await expect(page.locator('.ar-app')).toHaveClass(/is-dark/)
  await expect(page.locator('.agm-toast-title')).toHaveText('深色视界：开')
  const hud = page.getByRole('switch', { name: '显示 HUD' })
  await page.keyboard.press('h')
  await expect(hud).toHaveAttribute('aria-checked', 'false')
  await page.keyboard.press('h')
  await expect(hud).toHaveAttribute('aria-checked', 'true')

  await page.getByRole('button', { name: '语音指令', exact: true }).click()
  const input = page.getByRole('textbox', { name: '输入指令' })
  await input.focus()
  await page.keyboard.type('wdh?')
  await expect(input).toHaveValue('wdh?')
  await expect(page.getByRole('heading', { name: '语音指令' })).toBeVisible()
  await expect(page.locator('.ar-app')).toHaveClass(/is-dark/)
  await expect(page.getByRole('dialog')).toHaveCount(0)

  // Escape closes the open app even when focus has left it.
  await page.mouse.click(80, 400)
  await expect(page.locator('body')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.locator('.device-window')).toHaveCount(0)
})

test('shortcuts can be rebound with conflict checks, persisted, reset and turned off', async ({ page }) => {
  await page.goto('/ar/')
  await page.keyboard.press('?')
  const dialog = page.getByRole('dialog', { name: '键盘快捷键' })
  await expect(dialog).toBeVisible()
  const status = dialog.getByRole('status')

  const change = dialog.getByRole('button', { name: '更改「天气」的快捷键' })
  await change.click()
  await expect(status).toHaveText('为「天气」按下新按键。按 Esc 取消，Backspace 清除。')
  await page.keyboard.press('Enter')
  await expect(status).toHaveText('Enter 用于切换焦点、滚动或操作控件，请换一个。')
  await page.keyboard.press('F5')
  await expect(status).toHaveText('F5 已被浏览器或系统占用，请换一个。')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await expect(change).toHaveAttribute('aria-pressed', 'false')

  await change.click()
  await page.keyboard.press('d')
  await expect(status).toHaveText('D 已用于「切换深色视界」。再按一次改给「天气」，或按其他按键。')
  await page.keyboard.press('d')
  await expect(status).toHaveText('「天气」已设为 D，「切换深色视界」的快捷键已清除。')
  await dialog.getByRole('button', { name: '完成' }).click()
  await expect(dialog).toHaveCount(0)

  await page.reload()
  await expect(page.getByRole('button', { name: '天气', exact: true })).toHaveAttribute('aria-keyshortcuts', 'D')
  await page.keyboard.press('d')
  await expect(page.locator('.device-window--weather')).toBeVisible()
  await expect(page.locator('.ar-app')).not.toHaveClass(/is-dark/)
  await page.keyboard.press('Escape')
  await page.keyboard.press('w')
  await expect(page.locator('.device-window')).toHaveCount(0)

  await page.keyboard.press('?')
  await dialog.getByRole('button', { name: '恢复「天气」的默认快捷键' }).click()
  await expect(status).toHaveText('已恢复「天气」的默认快捷键。')
  await dialog.getByRole('button', { name: '恢复默认快捷键' }).click()
  await expect(dialog.getByRole('button', { name: /^恢复「/ })).toHaveCount(0)

  await dialog.getByRole('switch', { name: '启用键盘快捷键' }).click()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.keyboard.press('w')
  await expect(page.locator('.device-window')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '天气', exact: true })).not.toHaveAttribute('aria-keyshortcuts')

  await page.getByRole('button', { name: '系统菜单', exact: true }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const enabled = page.getByRole('switch', { name: '启用键盘快捷键' })
  await expect(enabled).not.toBeChecked()
  await page.reload()
  await page.keyboard.press('w')
  await expect(page.locator('.device-window')).toHaveCount(0)
  await page.getByRole('button', { name: '系统菜单', exact: true }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await enabled.click()
  await page.getByRole('button', { name: '查看与自定义', exact: true }).click()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '查看与自定义', exact: true })).toBeFocused()
})

test('shortcut sheet and command panel follow the macOS app voice menu key', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(window, 'webkit', { value: { messageHandlers: { speechCommand: { postMessage: () => {} } } } })
    Object.defineProperty(window, '__AUGMA_DESKTOP_VOICE_SHORTCUT__', { value: 'Alt+Meta+v', writable: true })
  })
  const setMenuKey = (shortcut: string | null) => page.evaluate(value => window.dispatchEvent(new CustomEvent('augma:voice-shortcut', { detail: { shortcut: value } })), shortcut)
  await page.goto('/ar/')
  await page.keyboard.press('?')
  const dialog = page.getByRole('dialog', { name: '键盘快捷键' })
  const row = dialog.locator('.shortcut-row', { hasText: '开始或结束语音指令（App 菜单）' })
  await expect(row.locator('kbd')).toHaveText(['⌥', '⌘', 'V'])
  await setMenuKey('Ctrl+Meta+F5')
  await expect(row.locator('kbd')).toHaveText(['⌃', '⌘', 'F5'])
  await setMenuKey(null)
  await expect(row).toHaveCount(0)
  await page.keyboard.press('Escape')

  await page.getByRole('button', { name: '语音指令', exact: true }).click()
  await expect(page.getByText('单次录音最长 12 秒。')).toBeVisible()
  await setMenuKey('Alt+Meta+v')
  await expect(page.getByText('按 ⌥⌘V 可控制录音，单次最长 12 秒。')).toBeVisible()
})

test('shortcut sheet fits a phone screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/ar/')
  await page.keyboard.press('?')
  const sheet = page.locator('.agm-dialog')
  await expect(sheet).toBeVisible()
  expect(await sheet.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  const box = await sheet.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
})
